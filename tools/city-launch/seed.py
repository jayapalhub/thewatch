#!/usr/bin/env python3
"""Write <slug>_*.sql (from gen.py) as a seed module in the repo and rebuild the seed index. usage: seed.py <name> <slug> [<slug>...]"""
import glob, json, os, re, sys
D = os.environ.get("CITY_DATA", os.path.dirname(os.path.abspath(__file__))); R = "/home/claude/thewatch/functions/_lib/seeds"
name, slugs = sys.argv[1], sys.argv[2:]
stmts = []
for s in slugs:
    for f in sorted(glob.glob(f"{D}/{s}_[0-9][0-9].sql")):
        stmts += [l for l in open(f).read().split("\n") if l.strip()]
open(f"{R}/{name}.js", "w").write("// Generated by the city launch tooling; see functions/admin/seeds.js\nexport default " + json.dumps(stmts, indent=0) + ";\n")
mods = sorted(os.path.splitext(f)[0] for f in os.listdir(R) if f.endswith(".js") and f != "index.js")
idx = "// Generated: the seeds the admin can run.\n" + "".join(f'import s{i} from "./{m}.js";\n' for i, m in enumerate(mods)) + "export const SEEDS = {" + ", ".join(f'"{m}": s{i}' for i, m in enumerate(mods)) + "};\n"
open(f"{R}/index.js", "w").write(idx)
print(name, len(stmts), "statements;", "seeds:", mods)
